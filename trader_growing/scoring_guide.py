def show_guide(dim):
    g = GUIDE[dim]
    print("  📖 {} 维度参考（对照打分，别拍脑袋）:".format(g["name"]))
    for score, desc in g["levels"]:
        if score >= 90:
            mark = "✅"
        elif score >= 70:
            mark = "👍"
        elif score >= 50:
            mark = "⚡"
        else:
            mark = "🚨"
        print("    {} {:>3}分: {}".format(mark, score, desc))
