    if ttype == "calc_shares":
        sym = args.get("asset", "510300.SS")
        amount = args.get("amount", 1000)
        close = load_latest(sym)
        if close is None:
            return None, "本地数据缺失"
        px = float(close.iloc[-1])
        return round(amount / px), {"date": str(today), "price": round(px, 3)}

